def get_message():
    now = datetime.now(TZ)

    if MESSAGE_TYPE == "morning":
        return WEEKLY_MESSAGES[now.weekday()]

    if MESSAGE_TYPE == "holiday":
        return HOLIDAYS.get((now.month, now.day))

    raise ValueError(f"Неизвестный тип сообщения: {MESSAGE_TYPE}")


async def main():
    if not BOT_TOKEN or not GROUP_CHAT_ID:
        raise ValueError(
            "Не заданы BOT_TOKEN и GROUP_CHAT_ID."
        )

    now = datetime.now(TZ)
    message = get_message()

    if message is None:
        print("Сегодня нет праздника. Сообщение не отправляется.")
        return

    bot = Bot(token=BOT_TOKEN)

    try:
        await bot.initialize()

        # Каждую пятницу отправляем фотографию с поздравлением
        if MESSAGE_TYPE == "morning" and now.weekday() == 4:

            if not PHOTO_PATH.exists():
                raise FileNotFoundError(
                    f"Фото не найдено: {PHOTO_PATH}"
                )

            with open(PHOTO_PATH, "rb") as photo:
                await bot.send_photo(
                    chat_id=GROUP_CHAT_ID,
                    photo=photo,
                    caption=message
                )

            print("Пятничная фотография и поздравление отправлены!")

        else:
            await bot.send_message(
                chat_id=GROUP_CHAT_ID,
                text=message
            )

            print("Сообщение успешно отправлено!")

    finally:
        await bot.shutdown()


if __name__ == "__main__":
    asyncio.run(main())
